/* =================================================================
   Культура развивает — пулы упражнений по категориям.

   Пользователь выбирает категорию — ему выпадает случайное
   упражнение из её списка (повторы откладываются, пока не показаны
   остальные). Чтобы добавить упражнение — допишите объект в список
   нужной категории. id уникален в пределах всей платформы.

   Общие поля:  id, type, q (условие), hint? (подсказка),
                demo? (true — может попасть в «Попробуй прямо сейчас»)

   Типы и их поля:
     choice   options:[строка | {value, html}], answer, explain, before? (html над вариантами)
              any:true + explains:{вариант:'текст'} — «нет неправильного ответа»
     input    answers:['принимаемые ответы'], explain, before?, inputmode?
     count    line:'строка', target:'символ' — «сколько раз встречается»
     match    pairs:[['слово','пара'], …] — соединить пары
     order    items:['в правильном порядке', …] — нажимать по порядку
     sort     rounds:[{title, buckets:['А','Б'], items:[{t:'элемент', b:0|1}]}]
     schulte  size:3..5 — найти числа по порядку
     oddout   rounds:5 — найти отличающийся символ
     pairs    symbols:6 — найти пары (память)
     recall   mode:'choose'|'type', seconds, items:[…], decoys:[…]  (choose)
                                    text:'…', seconds                (type)
     sudoku   grid:[[..]] (0 — пусто, 4×4), solution:[[..]]
     free     min:N — придумать не менее N разных идей
     stroop   rounds:8 — назвать цвет чернил, а не слова
   ================================================================= */

