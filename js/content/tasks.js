const arrowSVG = deg => '<svg class="shape" viewBox="0 0 48 48" aria-hidden="true"><g transform="rotate(' + deg +
  ' 24 24)"><path d="M24 6 L36 22 H28 V42 H20 V22 H12 Z" fill="currentColor"/></g></svg>';
const gridSVG = filled => {
  let cells = '';
  [[0,0],[1,0],[0,1],[1,1]].forEach(([x,y], i)=>{
    cells += '<rect x="' + (4 + x*22) + '" y="' + (4 + y*22) + '" width="20" height="20" rx="3" ' +
      (i === filled ? 'fill="currentColor"' : 'fill="none" stroke="currentColor" stroke-width="2"') + '/>';
  });
  return '<svg class="shape" viewBox="0 0 48 48" aria-hidden="true">' + cells + '</svg>';
};

