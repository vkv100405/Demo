/* =================================================================
   Культура развивает — данные о регионах.

   Каждый регион — один блок. Порядок блоков = порядок на экране
   выбора культуры. Список упражнений (exercises) проходится сверху
   вниз — каждая строка списка = одно задание на экране. Тип (type)
   определяет, какой модуль из js/exercises/ его покажет:

     words    — «Запомни слова»
                { words:[{w, m, icon?}], pick? }      пул слов, показывается pick (4)
     quiz     — «Давай проверим»
                { questions:[{q, options, answer, explain, hint?, requires?}], pick? }
                                                      пул вопросов, задаётся pick (1);
                requires — слово из «Запомни слова»: вопрос выпадет только
                если это слово показывали
     ornament — «Восстанови последовательность»
                { intro, hint, tiles?, images?, fallbackFilter? }
     recipe   — «Рецепт по памяти» + «Восстанови порядок»
                { title, intro, steps[], food }

   Случайность:
   • pool-поля (words, questions) — из пула берётся pick штук;
   • group — если несколько заданий имеют одинаковое поле group, то
     в тренировке на месте первого из них покажется одно случайное
     из группы. Так можно держать несколько рецептов/орнаментов,
     а пользователь увидит один (количество заданий не меняется).

   Картинки (везде можно указать имя файла из assets/ или ссылку
   https://…; если картинка не загрузится — показывается заглушка):
     регион: thumb:'файл' — карточка региона на экране выбора;
             mascots:{ plain:'файл', glasses:'…', book:'…', cap:'…',
                       flex:'…', cook:'…', shapes:'…' } — позы маскота;
     words:  у слова image:'файл' (иначе иконка icon);
     ornament: tiles:['файл1','файл2',…] — плитки по порядку;
     recipe: food:'файл' (или короткое имя: tatarstan → food-tatarstan.png).
   Не указано — картинка берётся по имени из assets/ (см. README).

   Навык, который оценивает задание (memory / attention / logic),
   задан в модуле, но его можно переопределить полем skill.
   ================================================================= */

